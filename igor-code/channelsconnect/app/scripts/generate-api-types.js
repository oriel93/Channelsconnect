#!/usr/bin/env node

/**
 * Generate TypeScript types from OpenAPI/Swagger schema
 * This script fetches the swagger.json from the API and generates TypeScript types
 */

const fs = require('fs');
const path = require('path');
const http = require('http');

const API_URL = process.env.VITE_API_URL || 'http://localhost:3001';
const SWAGGER_PATH = '/api-json';
const OUTPUT_DIR = path.join(__dirname, '../lib/generated');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'api-types.ts');

// Ensure output directory exists
if (!fs.existsSync(OUTPUT_DIR)) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
}

async function fetchSwaggerSchema() {
  return new Promise((resolve, reject) => {
    const url = `${API_URL}${SWAGGER_PATH}`;
    console.log(`📥 Fetching Swagger schema from ${url}...`);

    http.get(url, (res) => {
      let data = '';
      
      res.on('data', (chunk) => {
        data += chunk;
      });

      res.on('end', () => {
        try {
          const schema = JSON.parse(data);
          resolve(schema);
        } catch (error) {
          reject(new Error(`Failed to parse JSON: ${error.message}`));
        }
      });
    }).on('error', (error) => {
      reject(new Error(`Failed to fetch schema: ${error.message}`));
    });
  });
}

function generateTypeScriptTypes(schema) {
  let output = `// Auto-generated API types from Swagger schema
// Do not edit this file manually - run 'npm run generate-api-types' to regenerate

`;

  // Generate types from schemas
  if (schema.components && schema.components.schemas) {
    output += '// Entity Types\n\n';
    
    for (const [name, definition] of Object.entries(schema.components.schemas)) {
      output += generateInterface(name, definition);
    }
  }

  // Generate API endpoint types
  if (schema.paths) {
    output += '\n// API Endpoints\n\n';
    output += 'export interface ApiEndpoints {\n';
    
    for (const [path, methods] of Object.entries(schema.paths)) {
      for (const [method, details] of Object.entries(methods)) {
        if (['get', 'post', 'put', 'patch', 'delete'].includes(method)) {
          const operationId = details.operationId || `${method}_${path.replace(/\//g, '_')}`;
          output += `  '${method.toUpperCase()} ${path}': {\n`;
          output += `    operationId: '${operationId}';\n`;
          
          // Request body type
          if (details.requestBody) {
            const content = details.requestBody.content?.['application/json'];
            if (content?.schema?.$ref) {
              const typeName = content.schema.$ref.split('/').pop();
              output += `    body: ${typeName};\n`;
            }
          }
          
          // Response type
          if (details.responses?.['200'] || details.responses?.['201']) {
            const response = details.responses['200'] || details.responses['201'];
            const content = response.content?.['application/json'];
            if (content?.schema?.$ref) {
              const typeName = content.schema.$ref.split('/').pop();
              output += `    response: ${typeName};\n`;
            } else if (content?.schema?.type === 'array' && content.schema.items?.$ref) {
              const typeName = content.schema.items.$ref.split('/').pop();
              output += `    response: ${typeName}[];\n`;
            }
          }
          
          output += `  };\n`;
        }
      }
    }
    
    output += '}\n';
  }

  return output;
}

function generateInterface(name, definition) {
  let output = `export interface ${name} {\n`;

  if (definition.properties) {
    for (const [propName, propDef] of Object.entries(definition.properties)) {
      const isRequired = definition.required?.includes(propName);
      const isNullable = propDef.nullable || false;
      const optional = !isRequired || isNullable ? '?' : '';
      
      let type = 'any';
      
      if (propDef.type === 'string') {
        type = 'string';
      } else if (propDef.type === 'number' || propDef.type === 'integer') {
        type = 'number';
      } else if (propDef.type === 'boolean') {
        type = 'boolean';
      } else if (propDef.type === 'array') {
        const itemType = propDef.items?.$ref ? propDef.items.$ref.split('/').pop() : 'any';
        type = `${itemType}[]`;
      } else if (propDef.$ref) {
        type = propDef.$ref.split('/').pop();
      }
      
      if (isNullable) {
        type += ' | null';
      }
      
      output += `  ${propName}${optional}: ${type};\n`;
    }
  }

  output += '}\n\n';
  return output;
}

async function main() {
  try {
    console.log('🚀 Starting API type generation...');
    
    const schema = await fetchSwaggerSchema();
    console.log('✅ Schema fetched successfully');
    
    const types = generateTypeScriptTypes(schema);
    
    fs.writeFileSync(OUTPUT_FILE, types);
    console.log(`✅ Types generated successfully: ${OUTPUT_FILE}`);
    
    // Also save the raw schema for reference
    const schemaFile = path.join(OUTPUT_DIR, 'swagger-schema.json');
    fs.writeFileSync(schemaFile, JSON.stringify(schema, null, 2));
    console.log(`📄 Schema saved: ${schemaFile}`);
    
  } catch (error) {
    console.error('❌ Error generating types:', error.message);
    console.error('\nMake sure the API server is running at', API_URL);
    process.exit(1);
  }
}

main();

